# ------------------------------------------------------------------------------------
# WHAT ARE COMMENTS
# ------------------------------------------------------------------------------------
"""
A comment is a note written inside the code to explain what the code does.

Python ignores comments during execution. They are only for developers
to understand the code better.

Comments help in:
    - Explaining logic
    - Making code easier to read
    - Helping other developers understand the program
"""

# ------------------------------------------------------------------------------------
# TYPES OF COMMENTS
# ------------------------------------------------------------------------------------
"""
1. SINGLE LINE COMMENT
   - Written using the special character '#'
   - Used for short explanations

   Example:
       # this is a single line comment


2. MULTI-LINE COMMENT
   - Written using triple quotes (''' ''' or """ """)
   - Used for longer explanations or documentation
"""

"""
Example of multi-line comment

This is a multi-line comment.
It can span multiple lines.
Used to explain larger sections of code.
"""

"""
DOCSTRING

A docstring (documentation string) is a special string written inside
a function, class, or module to describe what it does.

Docstrings are written using triple quotes (""" """).

They help developers understand the purpose, parameters, and behavior
of the code.

Example:
"""

